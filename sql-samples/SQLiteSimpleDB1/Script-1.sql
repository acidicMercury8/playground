CREATE TABLE Работники_аэропорта (
    Код_работника VARCHAR(255) PRIMARY KEY,
    ФИО_работника VARCHAR(255) NOT NULL,
    Год_рождения DATE,
    Пол VARCHAR(255),
    Должность VARCHAR(255),
    Стаж VARCHAR(255),
    Адрес VARCHAR(255),
    Телефон VARCHAR(255)
);

CREATE TABLE Самолеты (
    Код_самолета VARCHAR(255) PRIMARY KEY,
    Кол_во_мест INT,
    Название_самолета VARCHAR(255),
    Год_выпуска DATE,
    Грузоподъемность VARCHAR(255)
);

CREATE TABLE Расписание_вылетов (
    Код_вылета VARCHAR(255) PRIMARY KEY,
    Код_самолета VARCHAR(255),
    Стоимость INT,
    Номер_маршрута INT,
    Дата_и_время_вылета DATETIME,
    Маршрут INT,
    FOREIGN KEY (Код_самолета) REFERENCES Самолеты(Код_самолета)
);

CREATE TABLE Бригада (
    Код_бригады VARCHAR(255) PRIMARY KEY,
    Код_работника VARCHAR(255),
    Код_самолета VARCHAR(255),
    ФИО_работника VARCHAR(255),
    Номер_маршрута INT,
    Название_самолета INT,
    Код_вылета VARCHAR(255),
    FOREIGN KEY (Код_работника) REFERENCES Работники_аэропорта(Код_работника),
    FOREIGN KEY (Код_самолета) REFERENCES Самолеты(Код_самолета),
    FOREIGN KEY (Код_вылета) REFERENCES Расписание_вылетов(Код_вылета)
);

CREATE TABLE Ведомость_продажи_билетов (
    Код_продажи VARCHAR(255) PRIMARY KEY,
    Код_вылета VARCHAR(255),
    Дата_и_время_вылета DATETIME,
    Номер_рейса INT,
    ФИО_пассажира VARCHAR(255),
    Паспорт VARCHAR(255),
    FOREIGN KEY (Код_вылета) REFERENCES Расписание_вылетов(Код_вылета)
);

